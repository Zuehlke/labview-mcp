using System.Xml.Linq;
using LabVIEWMcp.Infra;
using LabVIEWMcp.Tests.Fakes;
using LabVIEWMcp.Tests.Support;
using LabVIEWMcp.Tools;
using Xunit;

namespace LabVIEWMcp.Tests.Infra;

/// <summary>
/// Text and ring values on the pylabview backend, from a user's report of 2026-11-19: a text ring
/// of CANopen abort codes (`0503 0000h – Toggle bit not alternated.`) came out of the composer as
/// `0503 0000h Ð Toggle bit ...`, and its `values` were dropped, so the ring answered 0, 1, 2.
///
/// pylabview writes heap and type text as MacRoman, LabVIEW on Windows reads the bytes as CP1252:
/// the en dash is MacRoman 0xD0, CP1252 `Ð`; `Größe 5 °C` was `Grš§e 5 ¡C`. Ring items, control
/// names, descriptions, comments and the VI description were all affected, and the reader made the
/// same mistake in the other direction, so a round trip through our own composer and reader looked
/// right while NI's export of the same VI showed the broken text.
///
/// THE FIXTURE IS THE REAL ARTEFACT: `Ring CP1252.vi` was generated by NI's converter (backend grpc)
/// and SAVED BY LABVIEW, with an en dash, umlauts, ° and µ in every kind of text and a uint32 ring
/// whose last value is 4294967295. NI's export of it reads exactly what <see cref="Source"/> says.
/// The reader is pinned to that file; the composer is then checked by a round trip through the
/// pinned reader. The tests run the bundled interpreter and SKIP without it.
/// </summary>
public sealed class PylabviewRingTextTests
{
    private static string Fixture =>
        Path.Combine(RepoTree.Root, "tests", "LabVIEWMCP.Tests", "Fixtures", "reader", "ring-cp1252",
                     "Ring CP1252.vi");

    /// <summary>The AIXML the fixture was generated from.</summary>
    private const string Source = """
        <?xml version="1.0" encoding="UTF-8"?>
        <VI _name="RingRepro.vi" description="Ring repro – Größe">
          <Control _name="Abort Code" style="Ring" type="uint32" items="0503 0000h – Toggle bit not alternated.,0504 0001h \2C comma\2C here,Größe 5 °C µs,max" values="[84082688,84148225,134217760,4294967295]" conIdx="0" connection="required" description="Ring – Beschreibung äöü." outputs="value:4200.value" uid="4200" uid_parent="root" value="84082688"/>
          <Indicator _name="Code Größe" type="uint32" conIdx="4" connection="recommended" description="Code." inputs="value:4200.value" uid="4201" uid_parent="root" value="0"/>
          <FreeLabel comment="Gibt den Wert weiter – °C" uid="4290" uid_parent="root"/>
        </VI>
        """;

    private const string Items = @"0503 0000h – Toggle bit not alternated.,0504 0001h \2C comma\2C here,Größe 5 °C µs,max";

    private static async Task<XElement> ReadAsync(string vi)
    {
        var setup = AixmlComposer.Locate(out _);
        Assert.NotNull(setup);
        var output = Path.Combine(Path.GetTempPath(), "reader-" + Guid.NewGuid().ToString("n")[..8] + ".xml");
        try
        {
            var result = await AixmlComposer.ReadAsync(setup, vi, output, 120, default);
            Assert.True(result.Written, result.Message);
            return XElement.Load(output);
        }
        finally
        {
            try { File.Delete(output); } catch (IOException) { }
        }
    }

    private static void AssertTextAsAuthored(XElement vi)
    {
        Assert.Equal("Ring repro – Größe", (string?)vi.Attribute("description"));
        var ring = vi.Descendants("Control").Single();
        Assert.Equal(Items, (string?)ring.Attribute("items"));
        Assert.Equal("[84082688,84148225,134217760,4294967295]", (string?)ring.Attribute("values"));
        Assert.Equal("Ring – Beschreibung äöü.", (string?)ring.Attribute("description"));
        Assert.Equal("Code Größe", (string?)vi.Descendants("Indicator").Single().Attribute("_name"));
        Assert.Equal("Gibt den Wert weiter – °C", (string?)vi.Descendants("FreeLabel").Single().Attribute("comment"));
    }

    [Fact]
    public async Task The_reader_reads_a_LabVIEW_saved_VI_as_NI_exports_it()
    {
        if (AixmlComposer.Locate(out _) is null) return;

        AssertTextAsAuthored(await ReadAsync(Fixture));
    }

    [Fact]
    public async Task Composed_text_and_ring_values_read_back_as_authored()
    {
        if (AixmlComposer.Locate(out _) is null) return;
        await using var server = await LvaiTestServer.StartAsync();
        var xml = server.TempPath("ring.xml");
        var vi = server.TempPath("ring.vi");
        await File.WriteAllTextAsync(xml, Source);

        var composed = await new AixmlTools(server.Connection).ConvertAixmlToViAsync(
            xml, vi, checkExecutable: false, backend: "pylabview");
        Assert.Equal(0, Res.Int(composed, "errorCode"));

        AssertTextAsAuthored(await ReadAsync(vi));
    }

    [Fact]
    public async Task A_ring_value_beyond_32_bits_is_refused_by_name()
    {
        if (AixmlComposer.Locate(out _) is null) return;
        await using var server = await LvaiTestServer.StartAsync();
        var xml = server.TempPath("ring-wide.xml");
        await File.WriteAllTextAsync(xml, Source.Replace(",4294967295]", ",4294967296]"));

        var composed = await new AixmlTools(server.Connection).ConvertAixmlToViAsync(
            xml, server.TempPath("ring-wide.vi"), checkExecutable: false, backend: "pylabview");

        Assert.NotEqual(0, Res.Int(composed, "errorCode"));
        Assert.Contains("outside 32 bits", Res.Str(composed, "errorMessage"));
    }
}
